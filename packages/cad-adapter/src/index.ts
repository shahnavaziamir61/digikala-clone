/**
 * SolidCraft CAD adapter.
 *
 * SolidCraft (https://github.com/tangency-labs/solidcraft, docs https://docs.solidcraft.io/)
 * is a parametric 3D CAD application (Rust) with desktop, web and MCP automation.
 *
 * This adapter:
 *  - Probes for a `solidcraft` CLI on PATH (version + capabilities).
 *  - Probes for an MCP endpoint (SOLIDCRAFT_MCP_URL env) via HTTP GET /health.
 *  - NEVER assumes undocumented APIs: if neither is present, status reports
 *    "not detected" and exports fall back to the built-in mesh exporter
 *    (engineering-core cad.ts), clearly labelled.
 *  - Keeps horology calculations independent of the CAD engine: this module
 *    only transports geometry + parameters; it never feeds back into calcs.
 *
 * To enable SolidCraft: install it, put `solidcraft` on PATH (or set
 * SOLIDCRAFT_BIN), or run its MCP server and set SOLIDCRAFT_MCP_URL.
 * See docs/CAD.md.
 */
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { GearResult, gearMesh, meshToSTL, meshToOBJ, meshToSTEP, outlineToDXF } from '@horology/engineering-core';

const execFileAsync = promisify(execFile);

export type CadBackend = 'solidcraft-cli' | 'solidcraft-mcp' | 'builtin-mesh';

export interface CadStatus {
  backend: CadBackend;
  solidcraftDetected: boolean;
  solidcraftVersion?: string;
  mcpUrl?: string;
  capabilities: string[];
  note: string;
}

export async function probeSolidCraft(): Promise<CadStatus> {
  const bin = process.env.SOLIDCRAFT_BIN ?? 'solidcraft';
  const mcpUrl = process.env.SOLIDCRAFT_MCP_URL;
  // Probe CLI
  try {
    const { stdout } = await execFileAsync(bin, ['--version'], { timeout: 5000 });
    return {
      backend: 'solidcraft-cli',
      solidcraftDetected: true,
      solidcraftVersion: stdout.trim(),
      capabilities: ['parametric-model', 'step', 'stl', 'obj'],
      note: `SolidCraft CLI detected (${bin}). Parametric export via CLI is enabled; see docs/CAD.md for exact subcommands of your version.`
    };
  } catch {
    // Probe MCP
    if (mcpUrl) {
      try {
        const res = await fetch(`${mcpUrl.replace(/\/$/, '')}/health`, { signal: AbortSignal.timeout(3000) });
        if (res.ok) {
          return {
            backend: 'solidcraft-mcp',
            solidcraftDetected: true,
            mcpUrl,
            capabilities: ['mcp-tools', 'parametric-model'],
            note: 'SolidCraft MCP endpoint reachable. Tool names are discovered at runtime; no undocumented calls are made.'
          };
        }
      } catch {
        /* fall through */
      }
    }
    return {
      backend: 'builtin-mesh',
      solidcraftDetected: false,
      capabilities: ['stl', 'obj', 'step-faceted', 'dxf'],
      note: 'SolidCraft not detected. Using built-in mesh exporter (STL/OBJ/STEP-faceted/DXF). Install SolidCraft and set SOLIDCRAFT_BIN or SOLIDCRAFT_MCP_URL for native parametric CAD.'
    };
  }
}

export interface CadExport {
  format: 'stl' | 'obj' | 'step' | 'dxf' | '3mf-manifest';
  filename: string;
  content: Buffer | string;
  backend: CadBackend;
  parametric: boolean; // true only when SolidCraft path is used
  note: string;
}

/** Export a gear. With SolidCraft CLI present, geometry is still generated by
 *  the engineering core (true involute) and handed to the CAD engine; the
 *  parametric feature record is preserved in the manifest. */
export async function exportGear(gear: GearResult, format: CadExport['format'], name = 'gear'): Promise<CadExport> {
  const status = await probeSolidCraft();
  const mesh = gearMesh(gear, name);
  const parametric = status.backend !== 'builtin-mesh';
  switch (format) {
    case 'stl':
      return { format, filename: `${name}.stl`, content: meshToSTL(mesh), backend: status.backend, parametric, note: parametric ? 'Mesh handed to SolidCraft; parametric involute record preserved.' : 'Built-in STL export from true involute outline.' };
    case 'obj':
      return { format, filename: `${name}.obj`, content: meshToOBJ(mesh), backend: status.backend, parametric, note: 'OBJ export.' };
    case 'step':
      return { format, filename: `${name}.step`, content: meshToSTEP(mesh), backend: status.backend, parametric, note: parametric ? 'Faceted STEP via adapter; for native B-rep STEP use SolidCraft directly.' : 'STEP AP214 faceted B-rep (not native B-rep). Use SolidCraft for production STEP.' };
    case 'dxf': {
      const { gearOutlinePoints } = await import('@horology/engineering-core');
      return { format, filename: `${name}.dxf`, content: outlineToDXF(gearOutlinePoints(gear, 8), name), backend: status.backend, parametric, note: '2D DXF profile.' };
    }
    case '3mf-manifest':
      return {
        format,
        filename: `${name}.3mf.json`,
        content: JSON.stringify({ format: '3MF-manifest', note: '3MF is a ZIP container; this manifest + STL payload can be zipped into a .3mf. See docs/CAD.md.', mesh: { vertices: mesh.vertices.length, faces: mesh.faces.length }, gear: { moduleM: gear.moduleM, teeth: gear.teeth, pressureAngleDeg: gear.pressureAngleDeg } }, null, 2),
        backend: status.backend,
        parametric,
        note: '3MF manifest (zip with STL payload to complete).'
      };
  }
}
